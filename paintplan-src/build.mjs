#!/usr/bin/env node
// PaintPlan build — zero dependencies (Node ≥ 18). Assembles src/ into one deployable folder per theme:
//   dist/<theme>/index.html (single file: CSS + JS inlined, worker created from a Blob → works offline / iOS Safari)
//   dist/<theme>/sw.js, manifest.webmanifest, icons
// Usage:
//   node build.mjs                       build all themes (src/themes/*/theme.json) into dist/
//   node build.mjs classic               build one theme
//   node build.mjs --out /tmp/x          other output dir
//   node build.mjs --deploy ../test-apps also copy each theme to <repo>/<theme.deploy> and the source to <repo>/paintplan-src/
//   node build.mjs --mark v2             (tests) add a marker so the build hash changes without touching the source
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto'; import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, 'src');
const read = p => fs.readFileSync(path.join(SRC, p), 'utf8');

// Engine fragments: concatenated inside `function ENGINE(){ … }` (the function is also stringified into the worker).
const ENGINE_PARTS = ['color', 'image-cache', 'filters', 'values', 'palette', 'mixing', 'value-color', 'edges', 'dispatch'].map(n => `worker/engine/${n}.js`);
// App modules, in load order (they share one script scope). `if` = include only when the theme's runtime config says so.
const MODULES = [
  'core/util.js', 'core/paint-library.js', 'core/config.js', 'core/store.js', 'worker/client.js', 'core/pipeline.js',
  'core/levels.js', 'ui/panel.js', 'ui/mode-info.js', 'ui/histogram.js', 'ui/scale-info.js',
  'core/storage.js', 'core/image.js', { file: 'core/sample.js', if: rt => rt.sample }, 'core/placement.js',
  'ui/render.js', 'core/geometry.js', 'ui/overlays.js', 'ui/gestures.js', 'ui/picker.js', 'ui/paint-picker.js', 'ui/export.js', 'ui/init.js',
  { file: 'ui/empty.js', if: rt => !rt.sample }, { file: 'ui/setup.js', if: rt => !!rt.setup },
  'ui/pwa.js', 'ui/boot.js',
];
const ASSETS = ['apple-touch-icon.png', 'icon-192.png', 'icon-512.png'];

const args = process.argv.slice(2);
const opt = k => { const i = args.indexOf(k); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const OUT = path.resolve(opt('--out') || path.join(ROOT, 'dist'));
const DEPLOY = opt('--deploy'); const MARK = opt('--mark') || '';
const themes = args.length ? args : fs.readdirSync(path.join(SRC, 'themes')).filter(t => fs.existsSync(path.join(SRC, 'themes', t, 'theme.json')));

function fill(tpl, vars) { return tpl.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in vars ? vars[k] : m)); }

function iconsInline(css, dir) {
  return css.replace(/\{\{icon:([\w-]+)\}\}/g, (m, n) => {
    const svg = fs.readFileSync(path.join(dir, 'icons', n + '.svg'), 'utf8').trim();
    return 'url("data:image/svg+xml,' + encodeURIComponent(svg).replace(/%20/g, ' ').replace(/%3D/g, '=').replace(/%3A/g, ':').replace(/%2F/g, '/').replace(/%27/g, "'").replace(/%28/g, '(').replace(/%29/g, ')') + '")';
  });
}

function buildTheme(id) {
  const tdir = path.join(SRC, 'themes', id);
  let T = JSON.parse(fs.readFileSync(path.join(tdir, 'theme.json'), 'utf8'));
  // "extends": "<theme>" → inherit that theme's settings, template, CSS, icons and assets; own theme.css is appended
  // (used for isolated previews, e.g. themes/preview = liquid-glass deployed to another folder with its own SW + storage)
  let bdir = tdir;
  if (T.extends) {
    bdir = path.join(SRC, 'themes', T.extends); const B = JSON.parse(fs.readFileSync(path.join(bdir, 'theme.json'), 'utf8'));
    T = { ...B, ...T, manifest: { ...B.manifest, ...T.manifest }, sw: { ...B.sw, ...T.sw }, runtime: { ...(B.runtime || {}), ...(T.runtime || {}) } };
  }
  const rt = T.runtime || {};
  const tfile = n => fs.existsSync(path.join(tdir, n)) ? path.join(tdir, n) : path.join(bdir, n);
  const body = fs.readFileSync(tfile('template.html'), 'utf8').replace(/\{\{> ([\w-]+)\}\}\n?/g, (m, n) => read(`partials/${n}.html`));
  let themeCss = iconsInline(fs.readFileSync(path.join(bdir, 'theme.css'), 'utf8'), bdir);
  if (bdir !== tdir && fs.existsSync(path.join(tdir, 'theme.css'))) themeCss += '\n' + iconsInline(fs.readFileSync(path.join(tdir, 'theme.css'), 'utf8'), bdir);
  if (rt.setup) themeCss += '/* Setup sections (generated from theme.json → runtime.setup) */\n' +
    ['secSetup', ...rt.setup.sections].map(id => `body:not(.setup) #${id}`).join(',') + '{display:none!important}\n' +
    (rt.setup.hide || []).map(id => `body.setup #${id}`).join(',') + '{display:none!important}\n';
  const mods = MODULES.filter(m => typeof m === 'string' || m.if(rt)).map(m => typeof m === 'string' ? m : m.file);
  const js = ["'use strict';", `/* PaintPlan · theme "${id}" · build {{BUILD}} — generated by build.mjs from src/ (edit the source, not this file) */`,
    `const THEME=${JSON.stringify({ id, build: '{{BUILD}}', ...rt, ...(MARK ? { mark: MARK } : {}) })};`,
    '/* ===== Image engine: pure functions, runs in a Web Worker (or on the main thread as fallback) ===== */',
    'function ENGINE(){', ...ENGINE_PARTS.map(read).map(s => s.replace(/\n$/, '')), '}',
    ...mods.map(read).map(s => s.replace(/\n$/, ''))].join('\n') + '\n';
  if (/<\/script/i.test(js)) throw new Error('module source must not contain </script');
  let html = fill(read('shell.html'), { theme: id, title: T.title, themeColor: T.themeColor, bodyAttr: T.bodyClass ? ` class="${T.bodyClass}"` : '',
    BASE_CSS: read('styles/base.css'), THEME_CSS: themeCss, BODY: body, JS: js });
  const manifest = fill(read('pwa/manifest.webmanifest'), T.manifest);
  const swTpl = fill(read('pwa/sw.js'), { theme: id, LEGACY: JSON.stringify(T.sw.legacyCaches || []), EXCLUDE: JSON.stringify(T.sw.exclude || []) });
  const assetPath = a => [tdir, bdir].map(d => path.join(d, 'assets', a)).find(f => fs.existsSync(f)) || path.join(SRC, 'assets', a);
  const h = crypto.createHash('sha256'); [html, manifest, swTpl].forEach(s => h.update(s)); ASSETS.forEach(a => h.update(fs.readFileSync(assetPath(a))));
  const BUILD = h.digest('hex').slice(0, 12);
  html = html.split('{{BUILD}}').join(BUILD);
  const out = path.join(OUT, id); fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'index.html'), html);
  fs.writeFileSync(path.join(out, 'sw.js'), swTpl.split('{{BUILD}}').join(BUILD));
  fs.writeFileSync(path.join(out, 'manifest.webmanifest'), manifest);
  ASSETS.forEach(a => fs.copyFileSync(assetPath(a), path.join(out, a)));
  console.log(`built ${id.padEnd(14)} ${BUILD}  ${(html.length / 1024).toFixed(1)} KB  → ${path.relative(process.cwd(), out) || out}`);
  return { id, T, out, BUILD };
}

function copyTree(from, to, skip = () => false) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (skip(e.name, a)) continue;
    if (e.isDirectory()) copyTree(a, b, skip); else if (e.isFile()) fs.copyFileSync(a, b);
  }
}

const built = themes.map(buildTheme);
if (DEPLOY) {
  const repo = path.resolve(DEPLOY);
  for (const b of built) {
    const dest = path.join(repo, b.T.deploy);
    for (const f of fs.readdirSync(b.out)) { fs.mkdirSync(dest, { recursive: true }); fs.copyFileSync(path.join(b.out, f), path.join(dest, f)); }
    console.log(`deployed ${b.id} → ${path.relative(repo, dest)}/`);
  }
  // versioned source (no build output, screenshots or node_modules)
  const srcDest = path.join(repo, 'paintplan-src');
  fs.rmSync(srcDest, { recursive: true, force: true });
  copyTree(SRC, path.join(srcDest, 'src'));
  for (const f of ['build.mjs', 'README.md', '.gitignore']) if (fs.existsSync(path.join(ROOT, f))) fs.copyFileSync(path.join(ROOT, f), path.join(srcDest, f));
  if (fs.existsSync(path.join(ROOT, 'research'))) copyTree(path.join(ROOT, 'research'), path.join(srcDest, 'research'));
  copyTree(path.join(ROOT, 'test'), path.join(srcDest, 'test'), (n) => n === 'node_modules' || n === 'out' || /\.(png|jpe?g)$/i.test(n) && n !== 'photo.jpg' && n !== 'replace.jpg' && n !== 'real.jpg');
  console.log('source → paintplan-src/');
}
